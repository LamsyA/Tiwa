import { readFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import preset from '../tailwind-preset.js';

// Every semantic colour the design system owns. Core Tailwind utilities never
// contain these names, so any token that does must come from the preset.
const CUSTOM_STEMS = [
  'brand',
  'surface',
  'surface-2',
  'text',
  'muted',
  'success',
  'warning',
  'danger',
  'accent',
  'focus',
  'border',
] as const;

const COLOR_UTILITIES = [
  'bg',
  'text',
  'border',
  'ring',
  'decoration',
  'divide',
  'outline',
  'placeholder',
  'caret',
  'accent',
  'fill',
  'stroke',
] as const;

function collectFiles(dir: string): string[] {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) return collectFiles(full);
    return full.endsWith('.tsx') && !full.endsWith('.test.tsx') ? [full] : [];
  });
}

/** All utility classes the preset can generate (plus font/radius/shadow maps). */
function expectedClasses(): Set<string> {
  const out = new Set<string>();
  const walk = (node: unknown, path: string[]) => {
    if (typeof node === 'string') {
      // Tailwind drops a `DEFAULT` key: colors.brand.DEFAULT → `bg-brand`.
      const base = path.filter((segment) => segment !== 'DEFAULT').join('-');
      for (const utility of COLOR_UTILITIES) out.add(`${utility}-${base}`);
      return;
    }
    if (node && typeof node === 'object') {
      for (const [key, value] of Object.entries(node)) walk(value, [...path, key]);
    }
  };
  walk((preset as { theme: { extend: { colors: unknown } } }).theme.extend.colors, []);
  const extend = (preset as { theme: { extend: Record<string, Record<string, unknown>> } }).theme.extend;
  for (const key of Object.keys(extend.fontFamily ?? {})) out.add(`font-${key}`);
  for (const key of Object.keys(extend.borderRadius ?? {})) out.add(`rounded-${key}`);
  for (const key of Object.keys(extend.boxShadow ?? {})) out.add(`shadow-${key}`);
  for (const key of Object.keys(extend.transitionTimingFunction ?? {})) out.add(`ease-${key}`);
  return out;
}

/** Strip variant prefixes (hover:, md:, data-[...]:, ...) to the base utility. */
function baseUtility(token: string): string {
  const parts = token.split(':');
  return parts[parts.length - 1] ?? token;
}

describe('tailwind preset coverage', () => {
  it('every semantic token used in components is generated by the preset', () => {
    const expected = expectedClasses();
    const files = collectFiles(join(__dirname));
    const unknown: string[] = [];
    const tokenRe =
      /[A-Za-z0-9_.\-[\]()/=,]+:((?:bg|text|border|ring|decoration|divide|outline|placeholder|caret|accent|fill|stroke)-[a-z0-9-]+)|\b((?:bg|text|border|ring|decoration|divide|outline|placeholder|caret|accent|fill|stroke)-[a-z0-9]+)\b/g;
    for (const file of files) {
      const source = readFileSync(file, 'utf8');
      for (const match of source.matchAll(tokenRe)) {
        const token = (match[1] ?? match[2] ?? '') as string;
        if (!token) continue;
        if (!CUSTOM_STEMS.some((stem) => token === stem || token.includes(`-${stem}`) || token.endsWith(stem)))
          continue;
        const base = baseUtility(token);
        if (!expected.has(base)) unknown.push(`${file.split('packages/ui/src/')[1]}: ${token}`);
      }
    }
    expect(unknown, `unknown utilities (typos like text-on-brand?):\n${unknown.join('\n')}`).toEqual([]);
  });

  it('keeps on-* colours flat, never nested under a key literally named `on`', () => {
    // Tailwind v4's @config compat layer silently drops a nested colour key
    // literally named `on` (verified 2026-10-29: `text-brand-on` generated
    // zero CSS rules while the class sat in the DOM). Flat dashed keys
    // (`surface-2`) generate fine, so on-brand lives at the top level.
    const colours = (preset as { theme: { extend: { colors: Record<string, unknown> } } }).theme.extend.colors;
    expect(Object.keys(colours)).toContain('on-brand');
    for (const [key, value] of Object.entries(colours)) {
      if (value && typeof value === 'object') {
        expect(Object.keys(value), `nested "on" key under colours.${key}`).not.toContain('on');
      }
    }
    expect(expectedClasses().has('text-on-brand')).toBe(true);
  });
});
